internal fun unsplashEntry(
    id: String,
    photoSlug: String,
    title: String,
    description: String,
    category: WallpaperCategory,
    extraCollections: List<DiscoveryCollection>,
    resolutionTier: ResolutionTier,
    aspectRatio: String,
    dominantColors: List<Long>,
    colorFamily: ColorFamily,
    tags: List<String>,
    creatorName: String,
    supportsDepthEffect: Boolean = false,
    depthHint: DepthSubjectHint = DepthSubjectHint.LOWER_SILHOUETTE,
    popularityScore: Int = 82,
    addedOrder: Int = 1,
    fallbackResId: Int = when (category) {
        WallpaperCategory.AMOLED, WallpaperCategory.SPACE, WallpaperCategory.FUTURISTIC -> R.drawable.img_fallback_amoled_horizon
        WallpaperCategory.DEPTH_STUDIO, WallpaperCategory.NATURE -> R.drawable.img_fallback_depth_botanical
        WallpaperCategory.ARCHITECTURE, WallpaperCategory.MINIMALIST -> R.drawable.img_auth_hero
        else -> R.drawable.img_fallback_pastel_abstract
    }
): Wallpaper {
    val (w, h) = when (resolutionTier) {
        ResolutionTier.UHD_4K -> when (aspectRatio) {
            "9:16" -> 2160 to 3840
            "2:3" -> 2160 to 3240
            "16:9" -> 3840 to 2160
            else -> 2160 to 3840
        }
        ResolutionTier.QHD_1440 -> when (aspectRatio) {
            "9:16" -> 1440 to 2560
            "2:3" -> 1440 to 2160
            "16:9" -> 2560 to 1440
            else -> 1440 to 2560
        }
        ResolutionTier.FHD_1080 -> when (aspectRatio) {
            "9:16" -> 1080 to 1920
            "2:3" -> 1080 to 1620
            "16:9" -> 1920 to 1080
            else -> 1080 to 1920
        }
    }
    val quality = when (resolutionTier) {
        ResolutionTier.UHD_4K -> 95
        ResolutionTier.QHD_1440 -> 92
        ResolutionTier.FHD_1080 -> 90
    }
    val baseCollections = buildList {
        addAll(extraCollections)
        if (resolutionTier == ResolutionTier.UHD_4K) add(DiscoveryCollection.ULTRA_HD_4K)
        if (supportsDepthEffect) add(DiscoveryCollection.DEPTH_STUDIO)
        add(DiscoveryCollection.COLOUR_COLLECTIONS)
    }.distinct()

    return Wallpaper(
        id = id,
        title = title,
        description = description,
        category = category,
        collections = baseCollections,
        thumbnailUrl = "https://images.unsplash.com/photo-$photoSlug?auto=format&fit=crop&crop=entropy,faces,center&w=720&h=1120&q=82",
        fullResUrl = "https://images.unsplash.com/photo-$photoSlug?auto=format&fit=crop&crop=entropy,faces,center&w=$w&h=$h&q=$quality",
        fallbackResId = fallbackResId,
        width = w,
        height = h,
        resolutionTier = resolutionTier,
        aspectRatio = aspectRatio,
        dominantColors = dominantColors,
        colorFamily = colorFamily,
        tags = tags,
        creatorName = creatorName,
        creatorSource = "Unsplash Curated Studio",
        isDownloadable = true,
        supportsDepthEffect = supportsDepthEffect,
        depthSubjectHint = depthHint,
        popularityScore = popularityScore,
        addedOrder = addedOrder
    )
}

internal fun bundledEntry(
    id: String,
    @androidx.annotation.DrawableRes resId: Int,
    title: String,
    description: String,
    category: WallpaperCategory,
    extraCollections: List<DiscoveryCollection>,
    dominantColors: List<Long>,
    colorFamily: ColorFamily,
    tags: List<String>,
    supportsDepthEffect: Boolean = true,
    depthHint: DepthSubjectHint = DepthSubjectHint.CENTER_PORTRAIT,
    popularityScore: Int = 96,
    addedOrder: Int = 150
): Wallpaper {
    val w = 2160
    val h = 3840
    val baseCollections = buildList {
        addAll(extraCollections)
        add(DiscoveryCollection.ULTRA_HD_4K)
        if (supportsDepthEffect) add(DiscoveryCollection.DEPTH_STUDIO)
        add(DiscoveryCollection.COLOUR_COLLECTIONS)
    }.distinct()

    return Wallpaper(
        id = id,
        title = title,
        description = description,
        category = category,
        collections = baseCollections,
        thumbnailUrl = "asset://unsplash.local/photo-bundled-$id?w=720&h=1120",
        fullResUrl = "asset://unsplash.local/photo-bundled-$id?w=$w&h=$h&q=95",
        fallbackResId = resId,
        width = w,
        height = h,
        resolutionTier = ResolutionTier.UHD_4K,
        aspectRatio = "9:16",
        dominantColors = dominantColors,
        colorFamily = colorFamily,
        tags = tags,
        creatorName = "BACKDROP Studio",
        creatorSource = "BACKDROP Curated Originals",
        isDownloadable = true,
        supportsDepthEffect = supportsDepthEffect,
        depthSubjectHint = depthHint,
        popularityScore = popularityScore,
        addedOrder = addedOrder,
        isBundledAsset = true
    )
}

